/**
 * What importing an Exact division would do, before it does it (spec 13).
 *
 * "A dry-run mode producing a reconciliation report against the source
 * system's trial balance before anything is committed."
 *
 * That sentence is the whole design of this module. The plan is a pure function
 * of what was read from Exact and what already exists here — no database, no
 * clock, no network — so the report a human approves is exactly the thing that
 * gets executed, rather than a preview generated by a second code path that
 * might disagree with the first.
 *
 * ## What is reconciled, and why it is these three things
 *
 * The Exact importer brings master data and open items across, not history —
 * history is what the XAF import is for. So there is no set of postings to
 * compare against a trial balance line by line. What there is, and what an
 * accountant would actually ask for, is three questions:
 *
 * 1. **Does Exact's own trial balance balance?** If debit and credit do not
 *    agree in the source, nothing downstream of it can be trusted, and finding
 *    that out after the import is finding it out too late.
 * 2. **Do the open items add up to the control accounts?** Exact's receivables
 *    list should total to what its debtors account holds, and the payables list
 *    to its creditors account. When they agree, the open items we are about to
 *    import are provably the complete debtor and creditor position. When they
 *    do not, something in Exact is booked to the control account without an
 *    open item behind it, and importing the list would start us short.
 * 3. **Is every account the trial balance mentions in the chart we are
 *    importing?** A code with a balance and no account is a line that would
 *    have nowhere to land.
 *
 * The first is a `problem`. The other two are reported as differences with
 * their amounts, because a real migration often has a known and explicable one
 * — and refusing to proceed on a two-cent rounding difference in a
 * twelve-year-old administration would make the tool useless. What it must not
 * do is fail to mention it.
 */

/** Something wrong with what Exact returned, or with what it would mean here. */
export type ExactProblemCode =
  | 'trial_balance_unbalanced'
  | 'trial_balance_account_missing'
  | 'open_items_do_not_reconcile'
  | 'no_control_account'
  | 'account_number_collision'
  | 'contact_number_collision'
  | 'unknown_currency'
  | 'derived_account_type'
  | 'unknown_tax_code'
  | 'payment_term_not_representable'
  | 'attachment_without_url'
  | 'division_caution'
  | 'resource_unreadable'
  | 'trial_balance_empty'

export interface ExactProblem {
  readonly code: ExactProblemCode
  readonly path: string | null
  readonly message: string
}

function problem(code: ExactProblemCode, path: string | null, message: string): ExactProblem {
  return { code, path, message }
}

/**
 * What to actually do about a 403, given what Exact was willing to say.
 *
 * Three different sentences, because they send somebody to three different
 * places. Telling a user to check their rights when the rights are fine and
 * the subscription is the problem wastes an afternoon.
 */
function diagnose(missing: UnreadableResource): string {
  if (missing.userHasRight === false) {
    return ` Exact confirms this user does not have GET rights on ${missing.resource} in this administration: check the roles on that user under Stamgegevens → Gebruikers, or connect as somebody who has them.`
  }
  if (missing.userHasRight === true) {
    return ` Exact says this user *does* have GET rights on ${missing.resource}, so the refusal is not their role — it is the administration's subscription not including the module, or the app registration's own data scoping.`
  }
  return ` Exact grants rights per resource rather than per scope, and would not answer whether this user has this one. It is one of four things: the user's roles on this administration, the subscription's modules, the administration itself, or the app registration's data scoping.`
}

