/**
 * Everything one division-scoped read pass collected.
 *
 * A snapshot rather than a client, so that planning is testable from a fixture
 * and a plan can be shown, stored and re-shown without asking Exact again.
 */
export interface ExactSnapshot {
  readonly division: ExactDivision
  readonly glAccounts: readonly ExactGLAccount[]
  readonly vatCodes: readonly ExactVatCode[]
  readonly accounts: readonly ExactAccount[]
  readonly paymentConditions: readonly ExactPaymentCondition[]
  readonly receivables: readonly ExactOpenItem[]
  readonly payables: readonly ExactOpenItem[]
  /**
   * `financial/ReportingBalance` for one year, both statuses.
   *
   * `null` when it could not be read, which is not the same as empty and must
   * not be allowed to look like it. An empty trial balance has debit equal to
   * credit, so it balances; treating an unread one as empty would report a
   * division as reconciled without having looked, and would report every open
   * item as a difference against a control account of zero.
   */
  readonly trialBalance: readonly ExactReportingBalance[] | null
  readonly year: number
  readonly documents: readonly ExactDocument[]
  readonly attachments: readonly ExactAttachment[]
  /** Resources the read pass was refused. Empty on a division that read cleanly. */
  readonly unreadable: readonly UnreadableResource[]
}

/**
 * A resource the read pass asked for and did not get.
 *
 * Exact's rights are per resource, not per scope: `vat/VATCodes` and
 * `financial/ReportingBalance` are both "Financial accounting", and a login can
 * be allowed the first and refused the second. So a division that reads fine
 * for six resources can answer 403 for the seventh, and that has to be a fact
 * the report carries rather than an exception that ends it.
 */
export interface UnreadableResource {
  /** The path asked for, e.g. `financial/ReportingBalance`. */
  readonly resource: string
  /** Exact's status. 403 is rights; 404 is a resource this division has not got. */
  readonly status: number
  readonly message: string
  /**
   * What `users/UserHasRights` said about this endpoint, if it was asked.
   *
   * A 403 from Exact has at least four causes and the error body distinguishes
   * none of them: the signed-in user's rights, the subscription's modules, the
   * division, and the app's own data scoping. This is the one of those Exact
   * will answer directly, so the report can say *which* thing to go and change
   * rather than listing the possibilities.
   *
   * `null` means the probe was not asked or could not be answered — it is
   * scoped `Organization administration`, and a login refused the resource can
   * be refused the question too. Not knowing is not a "no".
   */
  readonly userHasRight?: boolean | null
}

/** What this administration already has, so the plan can say new or existing. */
export interface ExactImportOptions {
  readonly entityId: string
  /** The entity's own currency. A division in another one is a problem. */
  readonly currency: string
  readonly existingAccountNumbers: readonly string[]
  readonly existingContactNumbers: readonly string[]
  readonly existingTaxCodes: readonly string[]
  /**
   * Exact's account types for the debtors and creditors control accounts: 20
   * and 22. Overridable because a division can have more than one of each, and
   * because a chart that was migrated into Exact from somewhere else sometimes
   * has them typed as `90 = General`.
   */
  readonly receivableAccountCodes?: readonly string[]
  readonly payableAccountCodes?: readonly string[]
}

