/**
 * One side of the open-items reconciliation.
 *
 * `outcome` rather than a boolean, because there are four answers and only one
 * of them is "no". "The control account and the open items disagree" is a
 * finding about the administration; "there was no trial balance to compare
 * against" is a finding about our access to it. A boolean would report the
 * second as the first, which is a diagnosis of somebody else's books that we
 * have not earned.
 */
export type ControlAccountOutcome = 'matches' | 'differs' | 'no_control_account' | 'not_reconciled'

export interface ControlAccountCheck {
  readonly side: 'receivable' | 'payable'
  /** The account codes in Exact this side was measured against. */
  readonly accountCodes: readonly string[]
  /**
   * What the trial balance says those accounts hold, as a positive amount.
   * Null when the trial balance could not be read.
   */
  readonly ledger: bigint | null
  /** What the open items add up to. Known either way — a different resource. */
  readonly openItems: bigint
  readonly difference: bigint | null
  readonly outcome: ControlAccountOutcome
  readonly itemCount: number
  /**
   * Open items issued before the reconciliation year.
   *
   * The comparison is against **one** reporting year's movement on the control
   * account, and an open item has no year — a receivable raised in 2024 and
   * still unpaid is part of today's debtor position and contributes nothing to
   * 2026's movement. So any of these means a difference is expected, and
   * reading it as a finding about the administration would be wrong.
   */
  readonly itemsBeforeYear: number
}

/**
 * Where the trial balance came from, or why it did not.
 *
 * Three states, not two, and the third is the one that caught me out. A real
 * administration answered `financial/ReportingBalance` with **200 and no
 * rows** — readable, and empty. Treated as "read", an empty trial balance has
 * debit equal to credit, so it reported *balanced* on the strength of no
 * evidence, and then reported the whole debtor position as a difference
 * against a control account of zero: a confident €1.4M accusation assembled
 * entirely out of nothing.
 *
 * That is the same failure this type already guarded against for `unreadable`,
 * arriving through the door left open next to it. "Read and empty" makes no
 * claims either.
 */
export type TrialBalanceSource = 'read' | 'empty' | 'unreadable'

export interface TrialBalanceReconciliation {
  readonly year: number
  /**
   * `read` is the only value under which anything below is a claim. Every
   * total is null otherwise — an unread year is not an empty one, and an empty
   * year is not a balanced one.
   */
  readonly source: TrialBalanceSource
  readonly totalDebit: bigint | null
  readonly totalCredit: bigint | null
  readonly balanced: boolean | null
  readonly accountCount: number | null
  readonly transactionCount: number | null
  /** Codes with a balance in Exact and no account in the chart we read. */
  readonly orphanAccountCodes: readonly string[]
  readonly receivable: ControlAccountCheck
  readonly payable: ControlAccountCheck
}

